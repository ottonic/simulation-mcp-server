// Analytic reference for fully developed pressure-driven flow in a square duct
// of side `width`, driven by a streamwise pressure gradient `gradient`. Values
// are in SI (m, Pa, Pa.s, kg/m3, s). The fixture is a 100 x 10 x 10 mm bar.
export const DUCT = {
  length: 0.1,
  width: 0.01,
  viscosity: 0.01,
  density: 1000,
  deltaP: 1,
} as const;
export const GRADIENT = DUCT.deltaP / DUCT.length;
export const KINEMATIC_VISCOSITY = DUCT.viscosity / DUCT.density;

// Series coefficient shared by the steady and transient (startup) solutions.
function ductSeries(y: number, z: number, factor: (lambda: number) => number): number {
  let sum = 0;
  for (let m = 1; m <= 79; m += 2)
    for (let n = 1; n <= 79; n += 2) {
      const lambda = Math.PI ** 2 * ((m / DUCT.width) ** 2 + (n / DUCT.width) ** 2);
      sum +=
        (Math.sin((m * Math.PI * y) / DUCT.width) *
          Math.sin((n * Math.PI * z) / DUCT.width) *
          factor(lambda)) /
        (m * n * ((m / DUCT.width) ** 2 + (n / DUCT.width) ** 2));
    }
  return sum;
}

export function analyticSteadyVelocity(y: number, z: number): number {
  return ((16 * GRADIENT) / (DUCT.viscosity * Math.PI ** 4)) * ductSeries(y, z, () => 1);
}

export function analyticTransientVelocity(time: number, y: number, z: number): number {
  return (
    ((16 * GRADIENT) / (DUCT.viscosity * Math.PI ** 4)) *
    ductSeries(y, z, (lambda) => 1 - Math.exp(-KINEMATIC_VISCOSITY * lambda * time))
  );
}

// Volumetric flow rate Q = integral of u_x over the square cross-section.
export function analyticFlux(): number {
  let sum = 0;
  for (let m = 1; m <= 79; m += 2)
    for (let n = 1; n <= 79; n += 2) sum += 1 / (m * m * n * n * (m * m + n * n));
  return (
    ((16 * GRADIENT * DUCT.width ** 2) / (DUCT.viscosity * Math.PI ** 4)) *
    ((4 * DUCT.width ** 2) / Math.PI ** 2) *
    sum
  );
}

export function ductSelection(inventory: Inventory) {
  const selected = barSelections(inventory);
  const faceAt = (x: number) =>
    inventory.entities.find(
      (entity) => entity.dimension === 2 && Math.abs(entity.center[0] - x) < 1e-8,
    );
  const groupAt = (x: number) =>
    selected.groups.find(
      (group) => group.dimension === 2 && group.entities.includes(faceAt(x)?.tag ?? -1),
    );
  const inlet = groupAt(0);
  const outlet = groupAt(DUCT.length);
  const walls = selected.groups.filter(
    (group) => group.dimension === 2 && group !== inlet && group !== outlet,
  );
  if (!inlet || !outlet || walls.length !== 4)
    throw new Error('Expected two duct ends and four duct walls');
  const volume = selected.groups.find((group) => group.dimension === 3);
  if (!volume) throw new Error('Expected one duct volume group');
  return { selected, volume, inlet, outlet, walls };
}

type DuctStudyInput = {
  inspected: { source: ArtifactRef; inspection: ArtifactRef };
  selection: ReturnType<typeof ductSelection>;
  mesh: { minSize: number; maxSize: number };
  regime: { mode: 'steady' } | { mode: 'transient'; timestep: number; steps: number };
  observations?: unknown[];
  acceptanceCriteria?: unknown[];
};

// Builds a laminar-flow study consumed by the production workflow, so the SIF
// under qualification is the one generated by `src/flow.ts`.
export function ductStudy({
  inspected,
  selection,
  mesh,
  regime,
  observations = [],
  acceptanceCriteria = [],
}: DuctStudyInput) {
  const { selected, volume, inlet, outlet } = selection;
  const surfaces = selected.groups.filter((group) => group.dimension === 2);
  return {
    schemaVersion: '1',
    name: 'Duct flow qualification',
    objective: 'Qualify pressure-driven laminar flow against the analytic duct solution.',
    model: { source: inspected.source, inspection: inspected.inspection },
    selections: selected.groups.map((group) => ({
      name: group.name,
      entities: group.entities.map((tag) => `${group.dimension}:${tag}`),
    })),
    mesh: { minSize: mesh.minSize, maxSize: mesh.maxSize, elementOrder: 1 },
    physics: {
      kind: 'laminar-flow',
      materials: [
        {
          selection: volume.name,
          density: { value: DUCT.density, units: 'kg/m3' },
          dynamicViscosity: { value: DUCT.viscosity, units: 'Pa.s' },
        },
      ],
      boundaries: surfaces.map((group) =>
        group.id === inlet.id
          ? {
              selection: group.name,
              kind: 'pressure' as const,
              pressure: { value: DUCT.deltaP, units: 'Pa' as const },
            }
          : group.id === outlet.id
            ? {
                selection: group.name,
                kind: 'pressure' as const,
                pressure: { value: 0, units: 'Pa' as const },
              }
            : { selection: group.name, kind: 'no-slip' as const },
      ),
      regime:
        regime.mode === 'steady'
          ? { mode: 'steady' as const }
          : {
              mode: 'transient' as const,
              initialVelocity: [0, 0, 0].map(() => ({
                value: 0,
                units: 'm/s' as const,
              })) as [
                { value: number; units: 'm/s' },
                { value: number; units: 'm/s' },
                { value: number; units: 'm/s' },
              ],
              time: {
                timestep: { value: regime.timestep, units: 's' as const },
                steps: regime.steps,
              },
            },
    },
    observations,
    acceptanceCriteria,
    assumptions: [],
  };
}

// Runs a study end to end through the production workflow and returns the run.
export async function executeDuctStudy(sim: Simulation, study: ReturnType<typeof ductStudy>) {
  const preparation = await sim.prepareStudy(study);
  const prepared = await waitForJob(sim, preparation.jobId);
  if (prepared.status !== 'succeeded')
    throw new Error(`Preparation failed: ${JSON.stringify(prepared.error)}`);
  const started = await sim.runStudy(prepared.prepared!);
  const run = await waitForRun(sim, started.runId);
  if (run.status !== 'succeeded') throw new Error(`Solve failed: ${JSON.stringify(run.error)}`);
  return run;
}

