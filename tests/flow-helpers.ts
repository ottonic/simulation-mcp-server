export type DuctVtu = {
  points: number[];
  velocity: number[];
  pressure: number[];
  connectivity: number[];
  offsets: number[];
  types: number[];
};

function arrayIn(block: string | undefined, name: string | undefined): number[] {
  if (!block) return [];
  for (const match of block.matchAll(/<DataArray\b([^>]*)>([\s\S]*?)<\/DataArray>/g)) {
    const declared = match[1]!.match(/\bName="([^"]+)"/)?.[1];
    if (declared === name) return match[2]!.trim().split(/\s+/).map(Number);
  }
  return [];
}

export function parseDuctVtu(text: string): DuctVtu {
  return {
    points: arrayIn(text.match(/<Points\b[^>]*>([\s\S]*?)<\/Points>/)?.[1], undefined),
    velocity: arrayIn(text.match(/<PointData\b[^>]*>([\s\S]*?)<\/PointData>/)?.[1], 'velocity'),
    pressure: arrayIn(text.match(/<PointData\b[^>]*>([\s\S]*?)<\/PointData>/)?.[1], 'pressure'),
    connectivity: arrayIn(text.match(/<Cells\b[^>]*>([\s\S]*?)<\/Cells>/)?.[1], 'connectivity'),
    offsets: arrayIn(text.match(/<Cells\b[^>]*>([\s\S]*?)<\/Cells>/)?.[1], 'offsets'),
    types: arrayIn(text.match(/<Cells\b[^>]*>([\s\S]*?)<\/Cells>/)?.[1], 'types'),
  };
}

// Boundary triangles are tet faces that occur exactly once in the volume mesh.
export function boundaryTriangles(vtu: DuctVtu): [number, number, number][] {
  const faces = new Map<string, { tri: [number, number, number]; count: number }>();
  for (let cell = 0; cell < vtu.offsets.length; cell++) {
    const start = cell === 0 ? 0 : vtu.offsets[cell - 1]!;
    const nodes = vtu.connectivity.slice(start, vtu.offsets[cell]!);
    if (nodes.length !== 4) continue;
    for (const [a, b, d] of [
      [0, 1, 2],
      [0, 1, 3],
      [0, 2, 3],
      [1, 2, 3],
    ] as const) {
      const tri = [nodes[a]!, nodes[b]!, nodes[d]!].sort((p, q) => p - q) as [
        number,
        number,
        number,
      ];
      const key = tri.join(',');
      const existing = faces.get(key);
      if (existing) existing.count++;
      else faces.set(key, { tri, count: 1 });
    }
  }
  return [...faces.values()].filter((f) => f.count === 1).map((f) => f.tri);
}

function triangleArea(
  a: [number, number, number],
  b: [number, number, number],
  c: [number, number, number],
): number {
  const ab = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
  const ac = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
  const cross = [
    ab[1]! * ac[2]! - ab[2]! * ac[1]!,
    ab[2]! * ac[0]! - ab[0]! * ac[2]!,
    ab[0]! * ac[1]! - ab[1]! * ac[0]!,
  ];
  return 0.5 * Math.hypot(cross[0]!, cross[1]!, cross[2]!);
}

// Volumetric flow rate through a plane x = planeX: integral of u_x dA using the
// P1 nodal field over each boundary triangle that lies in the plane.
export function planeFluxX(
  vtu: DuctVtu,
  triangles: [number, number, number][],
  planeX: number,
  tolerance = 1e-9,
): number {
  let flux = 0;
  for (const [i, j, k] of triangles) {
    const a: [number, number, number] = [
      vtu.points[3 * i]!,
      vtu.points[3 * i + 1]!,
      vtu.points[3 * i + 2]!,
    ];
    const b: [number, number, number] = [
      vtu.points[3 * j]!,
      vtu.points[3 * j + 1]!,
      vtu.points[3 * j + 2]!,
    ];
    const c: [number, number, number] = [
      vtu.points[3 * k]!,
      vtu.points[3 * k + 1]!,
      vtu.points[3 * k + 2]!,
    ];
    if (
      Math.abs(a[0] - planeX) > tolerance ||
      Math.abs(b[0] - planeX) > tolerance ||
      Math.abs(c[0] - planeX) > tolerance
    )
      continue;
    const meanUx = (vtu.velocity[3 * i]! + vtu.velocity[3 * j]! + vtu.velocity[3 * k]!) / 3;
    flux += triangleArea(a, b, c) * meanUx;
  }
  return flux;
}

export function relativeL2(actual: number[], reference: number[]): number {
  let error = 0;
  let norm = 0;
  for (let i = 0; i < actual.length; i++) {
    error += (actual[i]! - reference[i]!) ** 2;
    norm += reference[i]! ** 2;
  }
  return Math.sqrt(error / norm);
}
